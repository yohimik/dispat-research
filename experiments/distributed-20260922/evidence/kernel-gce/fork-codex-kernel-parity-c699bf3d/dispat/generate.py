#!/usr/bin/env python3
# Writes dispat.yaml for the upstream ("master") matrix of this farm.
#
# The two lists are copied from master/master.cfg (stable_arches and
# qemu_targets_master). Every entry becomes one dispat package whose build
# stage runs the script buildbot runs for that builder, unchanged:
#   build-<arch>   -> bin/stable-build-arch.sh <arch> <branch>
#   qemu-<target>  -> rootfs/<target>/run-qemu-<target>.sh
#
#   python3 dispat/generate.py > dispat.yaml
import argparse
import json
import os
import subprocess

BUILD_ARCHES = [
    'alpha', 'arc', 'arcv2', 'arm', 'arm64', 'csky', 'hexagon', 'i386',
    'loongarch', 'm68k', 'm68k_nommu', 'mips', 'nios2', 'openrisc', 'parisc',
    'parisc64', 'powerpc', 'riscv32', 'riscv64', 's390', 'sh', 'sparc32',
    'sparc64', 'x86_64', 'xtensa', 'um',
]
QEMU_TARGETS = [
    'alpha', 'arm', 'arm-aspeed', 'arm-v7', 'arm64', 'm68k', 'mips', 'mipsel',
    'mips64', 'mipsel64', 'openrisc', 'parisc', 'ppc', 'ppc64', 'riscv32',
    'riscv64', 's390', 'sh', 'sheb', 'sparc', 'sparc64', 'x86', 'x86_64',
    'xtensa', 'parisc64', 'nios2', 'loongarch', 'arm64-rt', 'loongarch-rt',
    'riscv64-rt', 'x86_64-rt',
]
WORKERS = ['server', 'saturn', 'desktop', 'jupiter', 'mars', 'neptune']
MAILBOX = 'git@github.com:yohimik/linux-build-test-mailbox.git'

HEAD = '''# Generated by dispat/generate.py from the lists in master/master.cfg.
# Do not edit by hand: change the generator and run it again.
#
# One run tests one kernel revision, the one dispat/kernel/ref.env names.
# `kernel` is the package every cell of the matrix depends on, so a commit
#   feat(kernel)^^: test v7.3-rc4
# that changes ref.env puts every cell into the plan. A cell that passed is
# tagged and drops out of the next run; a cell that failed stays a candidate,
# so running again repeats the failures and nothing else.

logFormat: pretty
changelog: {enabled: false}
github: {enabled: false}
commit: {enabled: false}

# This history predates the commit convention dispat reads. Those commits
# contribute nothing and are counted rather than printed one by one.
parser: {quiet: true}

# A cell reads nothing the `kernel` package builds (it builds nothing), so
# every cell starts at once and only the records keep their order.
isBuildWaitingPublish: false

# Every cell runs on a worker. The machine that starts the run coordinates,
# records the results and spends no build slot of its own.
runOnly: %(runOnly)s

scripts:
  build-cell: ../../run-cell.sh
  build-config-cell: ../../../run-cell.sh
  qemu-cell: ../../dispat/run-cell.sh

execution:
  role: orchestrator
%(concurrency)s  secretEnv: DISPAT_EXECUTION_SECRET
  timeouts:
    preflight: 300
    # buildbot gives an image build 3600 s and a qemu target 1800 s
    task: %(task)d
    cancel: 120
'''


def build_configs(arch):
    """Read the farm's actual Bash array; do not maintain a second config list."""
    source = os.path.join(os.path.dirname(__file__), '..', 'bin', 'stable-build-targets.sh')
    result = subprocess.run(
        ['bash', '-c', 'source "$1"; name="cmd_${2}[@]"; printf "%s\\n" "${!name}"',
         'configs', source, arch], check=True, capture_output=True, text=True)
    configs = result.stdout.splitlines()
    if not configs or not all(configs):
        raise ValueError('No configurations for ' + arch)
    return configs


def canonical(key):
    """One spelling for a selector, so a batch may be named in any order."""
    arch, separator, configs = key.partition(':')
    if not separator:
        return arch
    return arch + ':' + '+'.join(sorted(configs.split('+')))


def cell_specs(values, option):
    """Read <arch>[:<config>] selectors, or <arch>[:<config>]=<value> settings.

    The result maps the one spelling of a selector to the spelling the operator
    wrote, which is the one a complaint should quote, and its setting.
    """
    specs = {}
    for value in values:
        for entry in value.split(','):
            if not entry:
                raise ValueError('%s has an empty entry' % option)
            key, _, setting = entry.partition('=')
            if canonical(key) in specs:
                raise ValueError('%s names %s twice' % (option, key))
            specs[canonical(key)] = (key, setting)
    return specs


def matching_spec(specs, arch, config):
    """The narrower selector wins: <arch>:<config> before <arch>.

    A batched package answers to the `+` spelling of its configurations, because
    a selector list is itself comma-separated.
    """
    keys = [] if config is None else [canonical(arch + ':' + config.replace(',', '+'))]
    for key in keys + [arch]:
        if key in specs:
            return key
    return None


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--workers', default=','.join(WORKERS),
                        help='comma-separated node names (default: the six build machines)')
    parser.add_argument('--mailbox', default=MAILBOX,
                        help='the Git repository the nodes coordinate through')
    parser.add_argument('--arches', default=','.join(BUILD_ARCHES),
                        help='comma-separated image build groups (default: all of master.cfg)')
    parser.add_argument('--qemu', default=','.join(QEMU_TARGETS),
                        help='comma-separated qemu targets; an empty value leaves them out')
    parser.add_argument('--task-timeout', type=int, default=3600,
                        help='seconds one cell may take (buildbot: 3600 without output)')
    parser.add_argument('--split-configs', action='store_true',
                        help='one image-build package per original configuration')
    parser.add_argument('--batch', action='append', default=[], metavar='ARCH:C1+C2',
                        help='keep these configurations in one package, in the original '
                             'order, so they share a build directory as the farm script '
                             'does (repeatable; needs --split-configs)')
    parser.add_argument('--jobs', type=int,
                        help='make jobs per image cell; budget this across worker slots')
    parser.add_argument('--cell-jobs', action='append', default=[], metavar='SPEC=JOBS',
                        help='make jobs for one <arch>[:<config>] cell (repeatable)')
    parser.add_argument('--orchestrator', action='append', default=[], metavar='SPEC',
                        help='<arch>[:<config>] cells that run on the machine starting '
                             'the release rather than on a worker (repeatable)')
    parser.add_argument('--concurrency', type=int,
                        help="the orchestrator's own build capacity when it takes part")
    parser.add_argument('--no-workers', action='store_true',
                        help='run every cell on the machine that starts the release: '
                             'the same recipe on one node, with no worker to place on')
    parser.add_argument('--publish-on-orchestrator', action='store_true',
                        help='record a worker cell on the machine that started the run: '
                             'the publish stage carries no build, and leaving it on the '
                             'worker costs two poll round trips at the end of a release')
    parser.add_argument('--env', action='append', default=[], metavar='KEY=VALUE',
                        help='environment entry added to every image cell (repeatable)')
    parser.add_argument('--no-write-cells', action='store_true',
                        help='print the configuration without creating package folders')
    args = parser.parse_args()
    arches = [a for a in args.arches.split(',') if a]
    targets = [t for t in args.qemu.split(',') if t]
    if args.jobs is not None and args.jobs < 1:
        parser.error('--jobs must be positive')
    if args.concurrency is not None and args.concurrency < 1:
        parser.error('--concurrency must be positive')
    if any(arch not in BUILD_ARCHES for arch in arches):
        parser.error('unknown image architecture')
    try:
        placed = cell_specs(args.orchestrator, '--orchestrator')
        cell_jobs = cell_specs(args.cell_jobs, '--cell-jobs')
    except ValueError as error:
        parser.error(str(error))
    for written, jobs in cell_jobs.values():
        if not jobs.isdigit() or int(jobs) < 1:
            parser.error('--cell-jobs %s needs a positive job count' % written)
    common_env = {}
    for entry in args.env:
        key, separator, value = entry.partition('=')
        if not key or not separator:
            parser.error('--env wants KEY=VALUE, not %r' % entry)
        common_env[key] = value
    used = set()
    cells = []
    out = [(HEAD % {'task': args.task_timeout,
                    'runOnly': ('orchestrator' if args.no_workers else
                                '[worker, orchestrator]'
                                if args.publish_on_orchestrator else 'worker'),
                    'concurrency': ('' if args.concurrency is None else
                                    '  concurrency: %d\n' % args.concurrency)}).rstrip('\n')]
    if not args.no_workers:
        out.append('  workers:')
        for worker in args.workers.split(','):
            out.append('    - {name: %s, endpoint: %s}' % (worker, args.mailbox))
    out.append('')
    out.append('packages:')
    out.append('  kernel:')
    out.append('    path: dispat/kernel')
    out.append('    runOnly: orchestrator')
    out.append('    isBuildWaitingPublish: {build: none}')
    if args.batch and not args.split_configs:
        parser.error('--batch needs --split-configs')
    batches = {}
    for entry in args.batch:
        arch, separator, joined = entry.partition(':')
        members = joined.split('+')
        if not separator or len(members) < 2 or not all(members):
            parser.error('--batch wants <arch>:<config>+<config>, not %r' % entry)
        for member in members:
            if (arch, member) in batches:
                parser.error('--batch names %s:%s twice' % (arch, member))
            batches[(arch, member)] = members
    for arch in arches:
        configs = build_configs(arch) if args.split_configs else [None]
        for config in configs:
            members = batches.get((arch, config))
            if members is not None:
                if any(member not in configs for member in members):
                    parser.error('--batch names a configuration %s does not have' % arch)
                # The farm script runs a selection in the original order, and the
                # package stands where the first of its configurations stood.
                members = [candidate for candidate in configs if candidate in members]
                if config != members[0]:
                    continue
                config = ','.join(members)
            suffix = config.replace('/', '-').replace(',', '+') if config else None
            name = arch + '-' + suffix if suffix else arch
            folder = arch + '/' + suffix if suffix else arch
            out.append('  build-%s:' % name)
            out.append('    path: dispat/build/%s' % folder)
            out.append('    dependencies: [kernel]')
            out.append('    flow: {build: %s}' %
                       ('build-config-cell' if config else 'build-cell'))
            spec = matching_spec(placed, arch, config)
            if spec is not None:
                used.add(spec)
                out.append('    runOnly: orchestrator')
            env = dict(common_env)
            if config:
                env.update(FARM_ARCH=arch, FARM_CONFIG=config)
            jobs = args.jobs
            spec = matching_spec(cell_jobs, arch, config)
            if spec is not None:
                used.add(spec)
                jobs = int(cell_jobs[spec][1])
            if jobs is not None:
                env['FARM_BUILD_JOBS'] = str(jobs)
            if env:
                out.append('    env: ' + json.dumps(env))
            cells.append((folder, arch, config))
    unused = sorted(dict(list(placed.items()) + list(cell_jobs.items()))[key][0]
                    for key in (set(placed) | set(cell_jobs)) - used)
    if unused:
        parser.error('no cell matches ' + ', '.join(unused))
    for target in targets:
        out.append('  qemu-%s:' % target)
        out.append('    path: rootfs/%s' % target)
        out.append('    dependencies: [kernel]')
        out.append('    flow: {build: qemu-cell}')
    print('\n'.join(out))
    here = os.path.dirname(os.path.abspath(__file__))
    for folder, arch, config in ([] if args.no_write_cells else cells):
        folder = os.path.join(here, 'build', folder)
        os.makedirs(folder, exist_ok=True)
        with open(os.path.join(folder, 'cell'), 'w') as cell:
            cell.write('stable-build-arch.sh %s%s\n' %
                       (arch, ' <branch> ' + config if config else ''))


if __name__ == '__main__':
    main()
