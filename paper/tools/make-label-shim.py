#!/usr/bin/env python3
"""Write a label shim so the condensed report can reference results that only
the extended edition contains.

Usage:
  python3 tools/make-label-shim.py FULL_AUX OUT_TEX SOURCE.tex ...

FULL_AUX is the .aux the extended edition wrote (tectonic --keep-intermediates).
Every \\newlabel it holds whose key is not defined by a \\label in the given
SOURCE files is copied into OUT_TEX with its number prefixed by F, so that a
\\cref to such a label in the condensed report prints, for example,
"Proposition F73" and the reader knows to open the extended edition. Labels
the condensed report defines itself are left out, so nothing is defined twice.
"""
import pathlib
import re
import sys


def main():
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    aux, out, sources = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]), sys.argv[3:]
    local = set()
    for s in sources:
        local.update(re.findall(r'\\label\{([^}]+)\}', pathlib.Path(s).read_text()))
    plain = re.compile(r'^(\\newlabel\{([^}]+)\}\{\{)([^}]*)(\}.*)$')
    cref = re.compile(r'^(\\newlabel\{([^}]+)@cref\}\{\{\[[^\]]*\]\[[^\]]*\]\[[^\]]*\])([^}]*)(\}.*)$')
    lines, kept, skipped = [], 0, 0
    for line in aux.read_text().splitlines():
        if not line.startswith('\\newlabel{'):
            continue
        m = cref.match(line)
        if m:
            key = m.group(2)
            if key in local:
                skipped += 1
                continue
            lines.append(m.group(1) + 'F' + m.group(3) + m.group(4))
            kept += 1
            continue
        m = plain.match(line)
        if m:
            key = m.group(2)
            if key.endswith('@cref') or key in local:
                skipped += 1
                continue
            lines.append(m.group(1) + ('F' + m.group(3) if m.group(3) else '') + m.group(4))
            kept += 1
    header = ('% Generated by tools/make-label-shim.py from the extended edition\'s .aux.\n'
              '% Every number here carries an F: the result lives in the extended edition.\n'
              '% Do not edit; rebuild the extended edition and regenerate.\n')
    out.write_text(header + '\n'.join(lines) + '\n')
    print(f'{out}: {kept} external labels written, {skipped} local labels left to the condensed edition')


if __name__ == '__main__':
    main()
